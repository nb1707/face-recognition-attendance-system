let latestSessionId = null;


function getVideoCameraMetadata() {
    const cameraId =
        document.getElementById("cameraId").value;

    if (cameraId === "front_cam_01") {
        return {
            cameraId: "front_cam_01",
            location: "front cam",
            purpose: "Capture full classroom view"
        };
    }

    if (cameraId === "side_cam_02") {
        return {
            cameraId: "side_cam_02",
            location: "side cam",
            purpose: "Capture side angle view"
        };
    }

    return {
        cameraId: "unknown",
        location: "Unknown",
        purpose: "Unknown camera"
    };
}


function updateVideoCameraInfo() {
    const camera =
        getVideoCameraMetadata();

    document.getElementById(
        "videoCameraInfo"
    ).innerHTML =
        "Camera ID: " +
        camera.cameraId +
        "<br>" +
        "Location: " +
        camera.location +
        "<br>" +
        "Purpose: " +
        camera.purpose;
}


function setProcessingState(
    isProcessing
) {
    const processButton =
        document.getElementById(
            "processVideoButton"
        );

    if (!processButton) {
        return;
    }

    processButton.disabled =
        isProcessing;

    processButton.innerText =
        isProcessing
            ? "Processing..."
            : "Process Video";
}


function resetSessionResult() {
    latestSessionId = null;

    const sessionContainer =
        document.getElementById(
            "generatedSessionContainer"
        );

    const sessionText =
        document.getElementById(
            "generatedSessionId"
        );

    const summaryButton =
        document.getElementById(
            "viewSummaryButton"
        );

    if (sessionContainer) {
        sessionContainer.hidden = true;
    }

    if (sessionText) {
        sessionText.innerText = "";
    }

    if (summaryButton) {
        summaryButton.disabled = true;
    }
}


async function processVideo() {
    const className =
        document.getElementById(
            "className"
        ).value.trim();

    const sampleInterval =
        Number(
            document.getElementById(
                "sampleInterval"
            ).value
        );

    const detectionModeElement =
        document.getElementById(
            "detectionMode"
        );

    const detectionMode =
        detectionModeElement
            ? detectionModeElement.value
            : "tiled";

    const videoFile =
        document.getElementById(
            "videoFile"
        ).files[0];

    const camera =
        getVideoCameraMetadata();

    if (!className) {
        alert(
            "Please enter Class Name."
        );
        return;
    }

    if (
        !Number.isFinite(
            sampleInterval
        )
        ||
        sampleInterval <= 0
    ) {
        alert(
            "Sample Interval Seconds must be greater than 0."
        );
        return;
    }

    if (!videoFile) {
        alert(
            "Please select a video file."
        );
        return;
    }

    const allowedExtensions = [
        ".mp4",
        ".avi",
        ".mov",
        ".mkv"
    ];

    const lowerFileName =
        videoFile.name.toLowerCase();

    const isSupportedVideo =
        allowedExtensions.some(
            extension =>
                lowerFileName.endsWith(
                    extension
                )
        );

    if (!isSupportedVideo) {
        alert(
            "Unsupported video format. " +
            "Please select MP4, AVI, MOV, or MKV."
        );
        return;
    }

    resetSessionResult();
    setProcessingState(true);

    const formData =
        new FormData();

    // session_id is generated by the backend.
    formData.append(
        "class_name",
        className
    );

    formData.append(
        "camera_id",
        camera.cameraId
    );

    formData.append(
        "camera_location",
        camera.location
    );

    formData.append(
        "sample_interval_seconds",
        String(sampleInterval)
    );

    formData.append(
        "detection_mode",
        detectionMode
    );

    formData.append(
        "video",
        videoFile
    );

    const statusElement =
        document.getElementById(
            "videoStatus"
        );

    const resultElement =
        document.getElementById(
            "videoResult"
        );

    statusElement.innerText =
        "Processing video... Please wait.";

    resultElement.innerText = "";

    try {
        const response =
            await fetch(
                "/process-video",
                {
                    method: "POST",
                    body: formData
                }
            );

        const responseText =
            await response.text();

        let result;

        try {
            result = responseText
                ? JSON.parse(
                    responseText
                )
                : {};
        } catch {
            throw new Error(
                "Server returned invalid JSON: " +
                responseText
            );
        }

        resultElement.innerText =
            JSON.stringify(
                result,
                null,
                2
            );

        if (
            response.ok
            &&
            result.success
        ) {
            latestSessionId =
                result.session_id
                || null;

            statusElement.innerText =
                "Video processed successfully.";

            if (latestSessionId) {
                const sessionContainer =
                    document.getElementById(
                        "generatedSessionContainer"
                    );

                const sessionText =
                    document.getElementById(
                        "generatedSessionId"
                    );

                const summaryButton =
                    document.getElementById(
                        "viewSummaryButton"
                    );

                if (sessionText) {
                    sessionText.innerText =
                        latestSessionId;
                }

                if (sessionContainer) {
                    sessionContainer.hidden =
                        false;
                }

                if (summaryButton) {
                    summaryButton.disabled =
                        false;
                }
            } else {
                statusElement.innerText =
                    "Video processed, but the backend did not return a session ID.";
            }

        } else {
            statusElement.innerText =
                result.message
                    ? (
                        "Video processing failed: " +
                        result.message
                    )
                    : "Video processing failed.";
        }

    } catch (error) {
        statusElement.innerText =
            "Error while processing video.";

        resultElement.innerText =
            String(error);

    } finally {
        setProcessingState(false);
    }
}


function goToSummary() {
    if (!latestSessionId) {
        alert(
            "No generated session ID is available. " +
            "Please process a video first."
        );
        return;
    }

    window.location.href =
        "/video-summary-page?session_id=" +
        encodeURIComponent(
            latestSessionId
        );
}


window.addEventListener(
    "load",
    () => {
        updateVideoCameraInfo();
        resetSessionResult();
    }
);